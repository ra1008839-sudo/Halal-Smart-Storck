  /// Search halal stocks
  static List<Map<String, dynamic>> searchHalalStocks(String query) {
    final lowercaseQuery = query.toLowerCase();
    return halalStocks.where((stock) {
      return stock['symbol'].toString().toLowerCase().contains(lowercaseQuery) ||
          stock['name'].toString().toLowerCase().contains(lowercaseQuery);
    }).toList();
  }
  
